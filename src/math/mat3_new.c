#include <math/la.h>

t_mat3	mat3_zero(void)
{
	return ((t_mat3){0});
}

t_mat3	mat3_identity(void)
{
	return ((t_mat3){
		.m00 = 1,
		.m01 = 0,
		.m02 = 0,
		.m10 = 0,
		.m11 = 1,
		.m12 = 0,
		.m20 = 0,
		.m21 = 0,
		.m22 = 1,
	});
}
